-- DATA GOVERNANCE: classify and document data with tags, so it can be found, owned and audited.
CREATE TAG IF NOT EXISTS GOVERNANCE.DATA_OWNER COMMENT = 'Team accountable for the data';
CREATE TAG IF NOT EXISTS GOVERNANCE.DATA_DOMAIN ALLOWED_VALUES 'CLINICAL', 'FINANCE', 'OPERATIONS';
CREATE TAG IF NOT EXISTS GOVERNANCE.SENSITIVITY ALLOWED_VALUES 'PUBLIC', 'INTERNAL', 'CONFIDENTIAL', 'RESTRICTED';
CREATE TAG IF NOT EXISTS GOVERNANCE.PII_TYPE
    ALLOWED_VALUES 'NAME', 'EMAIL', 'PHONE', 'DOB', 'NATIONAL_ID', 'INSURANCE_ID'
    COMMENT = 'Kind of personal data. Columns with this tag are masked automatically (see V003).';

-- Table-level tags
ALTER TABLE CLINICAL.PATIENTS SET TAG
    GOVERNANCE.DATA_OWNER = 'hospital-data-team',
    GOVERNANCE.DATA_DOMAIN = 'CLINICAL',
    GOVERNANCE.SENSITIVITY = 'RESTRICTED';

-- Column-level tags: personal identifiers
ALTER TABLE CLINICAL.PATIENTS MODIFY COLUMN FULL_NAME      SET TAG GOVERNANCE.PII_TYPE = 'NAME';
ALTER TABLE CLINICAL.PATIENTS MODIFY COLUMN EMAIL          SET TAG GOVERNANCE.PII_TYPE = 'EMAIL';
ALTER TABLE CLINICAL.PATIENTS MODIFY COLUMN PHONE          SET TAG GOVERNANCE.PII_TYPE = 'PHONE';
ALTER TABLE CLINICAL.PATIENTS MODIFY COLUMN DATE_OF_BIRTH  SET TAG GOVERNANCE.PII_TYPE = 'DOB';
ALTER TABLE CLINICAL.PATIENTS MODIFY COLUMN AADHAAR_NUMBER SET TAG GOVERNANCE.PII_TYPE = 'NATIONAL_ID';
ALTER TABLE CLINICAL.PATIENTS MODIFY COLUMN INSURANCE_ID   SET TAG GOVERNANCE.PII_TYPE = 'INSURANCE_ID';

-- Column-level tags: confidential but not identifying
ALTER TABLE CLINICAL.PATIENTS MODIFY COLUMN DIAGNOSIS   SET TAG GOVERNANCE.SENSITIVITY = 'CONFIDENTIAL';
ALTER TABLE CLINICAL.PATIENTS MODIFY COLUMN BILL_AMOUNT SET TAG GOVERNANCE.SENSITIVITY = 'CONFIDENTIAL',
                                                                GOVERNANCE.DATA_DOMAIN = 'FINANCE';

-- Business documentation lives next to the data
COMMENT ON COLUMN CLINICAL.PATIENTS.AADHAAR_NUMBER IS 'National ID. Never export unmasked.';
COMMENT ON COLUMN CLINICAL.PATIENTS.BRANCH IS 'Hospital branch. Drives row-level access (V004).';
