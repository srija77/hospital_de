-- SENSITIVE DATA: row-level security. Doctors see only patients of the branches mapped to their role.
CREATE TABLE IF NOT EXISTS GOVERNANCE.BRANCH_ACCESS (ROLE_NAME VARCHAR, BRANCH VARCHAR)
    COMMENT = 'Which role may see which branch. Edit rows here, not the policy.';

INSERT INTO GOVERNANCE.BRANCH_ACCESS (ROLE_NAME, BRANCH)
    SELECT 'GOV_DOCTOR', 'Chennai'
    WHERE NOT EXISTS (SELECT 1 FROM GOVERNANCE.BRANCH_ACCESS WHERE ROLE_NAME = 'GOV_DOCTOR' AND BRANCH = 'Chennai');

CREATE ROW ACCESS POLICY IF NOT EXISTS GOVERNANCE.BRANCH_ROW_POLICY AS (branch_val VARCHAR) RETURNS BOOLEAN ->
    IS_ROLE_IN_SESSION('GOV_ADMIN')
    OR IS_ROLE_IN_SESSION('GOV_ANALYST')
    OR EXISTS (
        SELECT 1 FROM GOVERNANCE.BRANCH_ACCESS m
        WHERE m.BRANCH = branch_val AND IS_ROLE_IN_SESSION(m.ROLE_NAME)
    )
    COMMENT = 'Admin and analyst: all rows. Other roles: rows of mapped branches only.';

ALTER TABLE CLINICAL.PATIENTS ADD ROW ACCESS POLICY GOVERNANCE.BRANCH_ROW_POLICY ON (BRANCH);
