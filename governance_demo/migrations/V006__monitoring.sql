-- MONITORING: data quality, sensitive-data access, deployments, and an alert.
CREATE SCHEMA IF NOT EXISTS MONITORING COMMENT = 'Health and audit views for the data steward';

-- The pipeline role may now count rows for quality checks. It still gets masked PII
-- (it falls through to the masking ELSE branches).
ALTER ROW ACCESS POLICY GOVERNANCE.BRANCH_ROW_POLICY SET BODY ->
    IS_ROLE_IN_SESSION('GOV_ADMIN')
    OR IS_ROLE_IN_SESSION('GOV_ANALYST')
    OR IS_ROLE_IN_SESSION('GOV_DEPLOYER')
    OR EXISTS (
        SELECT 1 FROM GOVERNANCE.BRANCH_ACCESS m
        WHERE m.BRANCH = branch_val AND IS_ROLE_IN_SESSION(m.ROLE_NAME)
    );

-- 1. Data quality: one row per rule, PASS or FAIL. The deploy pipeline stops if any rule fails.
CREATE OR REPLACE VIEW MONITORING.DATA_QUALITY_CHECKS AS
WITH p AS (SELECT * FROM CLINICAL.PATIENTS),
checks AS (
    SELECT 'at_least_100_rows' AS CHECK_NAME, IFF(COUNT(*) >= 100, 0, 1) AS FAILED_ROWS FROM p
    UNION ALL SELECT 'patient_id_not_null', COUNT_IF(PATIENT_ID IS NULL) FROM p
    UNION ALL SELECT 'patient_id_unique', COUNT(*) - COUNT(DISTINCT PATIENT_ID) FROM p
    UNION ALL SELECT 'bill_not_negative', COUNT_IF(BILL_AMOUNT < 0) FROM p
    UNION ALL SELECT 'known_branch', COUNT_IF(BRANCH NOT IN ('Chennai', 'Bengaluru', 'Hyderabad')) FROM p
    UNION ALL SELECT 'admission_not_in_future', COUNT_IF(ADMITTED_ON > CURRENT_DATE()) FROM p
)
SELECT CHECK_NAME, FAILED_ROWS, IFF(FAILED_ROWS = 0, 'PASS', 'FAIL') AS STATUS, CURRENT_TIMESTAMP() AS CHECKED_AT
FROM checks;

-- 2. Who read the patient table, with which role (ACCOUNT_USAGE lags by up to ~3 hours)
CREATE OR REPLACE VIEW MONITORING.PII_ACCESS_LOG AS
SELECT a.QUERY_START_TIME, a.USER_NAME, q.ROLE_NAME, f.value:"objectName"::STRING AS OBJECT_NAME, q.QUERY_TEXT
FROM SNOWFLAKE.ACCOUNT_USAGE.ACCESS_HISTORY a,
     LATERAL FLATTEN(a.BASE_OBJECTS_ACCESSED) f,
     SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY q
WHERE q.QUERY_ID = a.QUERY_ID
  AND f.value:"objectName"::STRING ILIKE 'GOV_DEMO_%.CLINICAL.PATIENTS';

-- 3. What the pipeline deployed and when
CREATE OR REPLACE VIEW MONITORING.DEPLOYMENTS AS
SELECT VERSION, STATUS, APPLIED_AT, APPLIED_BY FROM CONTROL.MIGRATION_HISTORY;

-- 4. Alert: checks data quality every hour and logs failures.
-- Created suspended to avoid warehouse cost. Start it with: ALTER ALERT MONITORING.DATA_QUALITY_ALERT RESUME;
-- Or run it once on demand:  EXECUTE ALERT MONITORING.DATA_QUALITY_ALERT;
CREATE TABLE IF NOT EXISTS MONITORING.ALERT_LOG (
    ALERT_TIME TIMESTAMP_LTZ, CHECK_NAME VARCHAR, FAILED_ROWS NUMBER
);
CREATE OR REPLACE ALERT MONITORING.DATA_QUALITY_ALERT
    WAREHOUSE = GOV_DEMO_WH
    SCHEDULE = '60 MINUTE'
    IF (EXISTS (SELECT 1 FROM MONITORING.DATA_QUALITY_CHECKS WHERE STATUS = 'FAIL'))
    THEN
        INSERT INTO MONITORING.ALERT_LOG
        SELECT CURRENT_TIMESTAMP(), CHECK_NAME, FAILED_ROWS FROM MONITORING.DATA_QUALITY_CHECKS WHERE STATUS = 'FAIL';

-- Only the data steward reads monitoring
GRANT USAGE ON SCHEMA MONITORING TO ROLE GOV_ADMIN;
GRANT SELECT ON ALL VIEWS IN SCHEMA MONITORING TO ROLE GOV_ADMIN;
GRANT SELECT ON TABLE MONITORING.ALERT_LOG TO ROLE GOV_ADMIN;
