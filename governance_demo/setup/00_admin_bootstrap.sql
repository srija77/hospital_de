-- One-time setup, run manually by an ACCOUNTADMIN in Snowsight.
-- After this, every change goes through the CI/CD pipeline as GOV_DEPLOYER.
USE ROLE ACCOUNTADMIN;

-- Roles: one for the pipeline, three for people
CREATE ROLE IF NOT EXISTS GOV_DEPLOYER COMMENT = 'CI/CD service role: owns and deploys objects';
CREATE ROLE IF NOT EXISTS GOV_ADMIN    COMMENT = 'Data steward: sees all PII';
CREATE ROLE IF NOT EXISTS GOV_DOCTOR   COMMENT = 'Clinician: own branch only, identity visible, national ID partly masked';
CREATE ROLE IF NOT EXISTS GOV_ANALYST  COMMENT = 'Analyst: all branches, PII masked';
GRANT ROLE GOV_DEPLOYER TO ROLE SYSADMIN;
GRANT ROLE GOV_ADMIN    TO ROLE SYSADMIN;
GRANT ROLE GOV_DOCTOR   TO ROLE SYSADMIN;
GRANT ROLE GOV_ANALYST  TO ROLE SYSADMIN;

-- Compute
CREATE WAREHOUSE IF NOT EXISTS GOV_DEMO_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
GRANT USAGE ON WAREHOUSE GOV_DEMO_WH TO ROLE GOV_DEPLOYER;
GRANT USAGE ON WAREHOUSE GOV_DEMO_WH TO ROLE GOV_ADMIN;
GRANT USAGE ON WAREHOUSE GOV_DEMO_WH TO ROLE GOV_DOCTOR;
GRANT USAGE ON WAREHOUSE GOV_DEMO_WH TO ROLE GOV_ANALYST;

-- One database per environment, owned by the pipeline role
CREATE DATABASE IF NOT EXISTS GOV_DEMO_DEV;
CREATE DATABASE IF NOT EXISTS GOV_DEMO_PROD;
GRANT USAGE ON DATABASE GOV_DEMO_DEV  TO ROLE GOV_ADMIN;
GRANT USAGE ON DATABASE GOV_DEMO_DEV  TO ROLE GOV_DOCTOR;
GRANT USAGE ON DATABASE GOV_DEMO_DEV  TO ROLE GOV_ANALYST;
GRANT USAGE ON DATABASE GOV_DEMO_PROD TO ROLE GOV_ADMIN;
GRANT USAGE ON DATABASE GOV_DEMO_PROD TO ROLE GOV_DOCTOR;
GRANT USAGE ON DATABASE GOV_DEMO_PROD TO ROLE GOV_ANALYST;
GRANT OWNERSHIP ON DATABASE GOV_DEMO_DEV  TO ROLE GOV_DEPLOYER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE GOV_DEMO_PROD TO ROLE GOV_DEPLOYER COPY CURRENT GRANTS;

-- Governance privileges the pipeline needs (tag-based masking needs the account-level grant)
GRANT APPLY MASKING POLICY    ON ACCOUNT TO ROLE GOV_DEPLOYER;
GRANT APPLY ROW ACCESS POLICY ON ACCOUNT TO ROLE GOV_DEPLOYER;
GRANT APPLY TAG               ON ACCOUNT TO ROLE GOV_DEPLOYER;

-- Let the data steward read governance views in SNOWFLAKE.ACCOUNT_USAGE
GRANT DATABASE ROLE SNOWFLAKE.GOVERNANCE_VIEWER TO ROLE GOV_ADMIN;

