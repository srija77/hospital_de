 CHECK_ID VARCHAR,CHECK_NAME VARCHAR,TABLE_NAME VARCHAR,CHECK_TIMESTAMP TIMESTAMP_TZ,
 STATUS VARCHAR,FAILED_ROW_COUNT NUMBER,SEVERITY VARCHAR,DETAILS VARCHAR);
