CREATE TABLE IF NOT EXISTS MONITORING.PIPELINE_RUN_LOG (
 RUN_ID VARCHAR,PIPELINE_NAME VARCHAR,MODEL_NAME VARCHAR,STARTED_AT TIMESTAMP_TZ,
