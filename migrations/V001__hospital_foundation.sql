 BENCHMARK_ID VARCHAR,WORKLOAD_NAME VARCHAR,RUN_TIMESTAMP TIMESTAMP_TZ,CONFIGURATION_NAME VARCHAR,
 ELAPSED_SECONDS FLOAT,BYTES_SCANNED NUMBER,ROWS_RETURNED NUMBER,WAREHOUSE_NAME VARCHAR,
 CREDITS_USED FLOAT,CACHE_STATE VARCHAR,QUERY_ID VARCHAR,QUERY_TEXT VARCHAR,WAREHOUSE_SIZE VARCHAR,
 EXPERIMENT VARCHAR,VARIANT VARCHAR,EVIDENCE VARCHAR);

CREATE TAG IF NOT EXISTS GOVERNANCE.PII_CLASSIFICATION ALLOWED_VALUES 'SENSITIVE','INTERNAL';
-- The dbt post-hook binds this tag to every PII Gold column after each build.

CREATE MASKING POLICY IF NOT EXISTS GOVERNANCE.MASK_NAME AS (v VARCHAR) RETURNS VARCHAR ->
 CASE WHEN CURRENT_ROLE()='DE_ADMIN' THEN v ELSE 'MASKED' END;
CREATE MASKING POLICY IF NOT EXISTS GOVERNANCE.MASK_EMAIL AS (v VARCHAR) RETURNS VARCHAR ->
 CASE WHEN CURRENT_ROLE()='DE_ADMIN' THEN v ELSE '***@***' END;
CREATE MASKING POLICY IF NOT EXISTS GOVERNANCE.MASK_PHONE AS (v VARCHAR) RETURNS VARCHAR ->
 CASE WHEN CURRENT_ROLE()='DE_ADMIN' THEN v ELSE '**********' END;
CREATE MASKING POLICY IF NOT EXISTS GOVERNANCE.MASK_DOB AS (v DATE) RETURNS DATE ->
 CASE WHEN CURRENT_ROLE()='DE_ADMIN' THEN v ELSE NULL END;
-- Direct active-role comparison intentionally does not authorize inherited or secondary roles.
-- PROD Gold attachments happen inside the dbt table transaction post-hook.
