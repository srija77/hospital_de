 ALERT_KEY VARCHAR,ALERT_TYPE VARCHAR,DETECTED_AT TIMESTAMP_TZ,AFFECTED_OBJECT VARCHAR,
 MESSAGE VARCHAR,RECOMMENDED_ACTION VARCHAR,RECIPIENT VARCHAR);
