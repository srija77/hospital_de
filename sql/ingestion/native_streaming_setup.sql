-- Does not resume tasks or incur ingestion charges by itself. No PROD deployment here.
USE ROLE DE_ENGINEER;
USE DATABASE HOSPITAL_DEV;
ALTER TABLE BRONZE.ADMISSION_EVENTS ADD COLUMN IF NOT EXISTS SOURCE_PUBLISHED_AT TIMESTAMP_TZ;
CREATE PIPE IF NOT EXISTS BRONZE.ADMISSION_EVENTS_STREAM_PIPE AS
COPY INTO BRONZE.ADMISSION_EVENTS (RAW,LOADED_AT,SOURCE_FILE,SOURCE_PUBLISHED_AT)
FROM (SELECT $1:RAW,CURRENT_TIMESTAMP(),$1:SOURCE_FILE::VARCHAR,$1:SOURCE_PUBLISHED_AT::TIMESTAMP_TZ
      FROM TABLE(DATA_SOURCE(TYPE => 'STREAMING')));
CREATE STREAM IF NOT EXISTS BRONZE.ADMISSION_EVENTS_CDC
 ON TABLE BRONZE.ADMISSION_EVENTS APPEND_ONLY=TRUE SHOW_INITIAL_ROWS=TRUE;
