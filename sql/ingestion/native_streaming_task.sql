-- Opt-in DEV only; task remains suspended until an explicitly authorized RESUME.
USE ROLE DE_ENGINEER;
USE DATABASE HOSPITAL_DEV;
CREATE OR REPLACE PROCEDURE MONITORING.PROCESS_ADMISSION_STREAM()
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS CALLER AS
$$
DECLARE
 task_run_id VARCHAR DEFAULT UUID_STRING();
 started TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP();
 affected NUMBER DEFAULT 0;
BEGIN
 BEGIN TRANSACTION;
 MERGE INTO SILVER.ADMISSIONS t USING (
 SELECT v.* FROM SILVER.EVENT_CLASSIFICATION v
 JOIN (SELECT DISTINCT TRY_TO_NUMBER(RAW:admission_id::STRING) ADMISSION_ID
       FROM BRONZE.ADMISSION_EVENTS_CDC WHERE TRY_TO_NUMBER(RAW:admission_id::STRING) IS NOT NULL) changed
 ON v.ADMISSION_ID=changed.ADMISSION_ID
 WHERE v.IS_VALID
 QUALIFY ROW_NUMBER() OVER (PARTITION BY v.ADMISSION_ID
 ORDER BY v.EVENT_VERSION DESC,v.EVENT_TIME DESC,v.EVENT_ID DESC)=1
) s ON t.ADMISSION_ID=s.ADMISSION_ID
WHEN MATCHED AND (s.EVENT_VERSION>t.EVENT_VERSION OR
 (s.EVENT_VERSION=t.EVENT_VERSION AND s.EVENT_TIME>t.EVENT_TIME) OR
 (s.EVENT_VERSION=t.EVENT_VERSION AND s.EVENT_TIME=t.EVENT_TIME AND s.EVENT_ID>t.EVENT_ID))
THEN UPDATE SET PATIENT_ID=s.RAW:payload:patient_id::NUMBER,ADMIT_DATE=s.RAW:payload:admit_date::DATE,
 DISCHARGE_DATE=s.RAW:payload:discharge_date::DATE,DEPARTMENT=s.RAW:payload:department::VARCHAR,
 ADMISSION_TYPE=s.RAW:payload:admission_type::VARCHAR,BILL_AMOUNT=s.RAW:payload:bill_amount::NUMBER(18,2),
 STATUS=s.RAW:payload:status::VARCHAR,UPDATED_AT=s.RAW:payload:updated_at::TIMESTAMP_TZ,
 EVENT_VERSION=s.EVENT_VERSION,EVENT_TIME=s.EVENT_TIME,EVENT_ID=s.EVENT_ID
WHEN NOT MATCHED THEN INSERT
 (ADMISSION_ID,PATIENT_ID,ADMIT_DATE,DISCHARGE_DATE,DEPARTMENT,ADMISSION_TYPE,BILL_AMOUNT,STATUS,UPDATED_AT,EVENT_VERSION,EVENT_TIME,EVENT_ID)
VALUES (s.ADMISSION_ID,s.RAW:payload:patient_id::NUMBER,s.RAW:payload:admit_date::DATE,
 s.RAW:payload:discharge_date::DATE,s.RAW:payload:department::VARCHAR,s.RAW:payload:admission_type::VARCHAR,
 s.RAW:payload:bill_amount::NUMBER(18,2),s.RAW:payload:status::VARCHAR,
 s.RAW:payload:updated_at::TIMESTAMP_TZ,s.EVENT_VERSION,s.EVENT_TIME,s.EVENT_ID);

 affected := SQLROWCOUNT;
 MERGE INTO MONITORING.DATA_FRESHNESS t USING (
  SELECT 'SILVER.ADMISSIONS' DATASET_NAME,CURRENT_TIMESTAMP() LAST_LOAD,COUNT(*) ROW_COUNT FROM SILVER.ADMISSIONS
  UNION ALL SELECT 'BRONZE.ADMISSION_EVENTS',MAX(LOADED_AT),COUNT(*) FROM BRONZE.ADMISSION_EVENTS
 ) s ON t.DATASET_NAME=s.DATASET_NAME
 WHEN MATCHED THEN UPDATE SET LAST_SUCCESSFUL_LOAD=s.LAST_LOAD,EXPECTED_INTERVAL_MINUTES=60,
  FRESHNESS_STATUS='FRESH',ROW_COUNT=s.ROW_COUNT,LAST_CHECKED_AT=CURRENT_TIMESTAMP()
 WHEN NOT MATCHED THEN INSERT VALUES(s.DATASET_NAME,s.LAST_LOAD,60,'FRESH',s.ROW_COUNT,CURRENT_TIMESTAMP());
 INSERT INTO MONITORING.PIPELINE_RUN_LOG VALUES(
  :task_run_id,'hospital_native_stream','silver',:started,CURRENT_TIMESTAMP(),'SUCCESS',:affected,NULL);
 COMMIT;
 RETURN 'Stream consumed; version MERGE and telemetry committed together';
EXCEPTION WHEN OTHER THEN
 ROLLBACK;
 INSERT INTO MONITORING.PIPELINE_RUN_LOG VALUES(
  :task_run_id,'hospital_native_stream','silver',:started,CURRENT_TIMESTAMP(),'FAILED',0,'SQLCODE='||:SQLCODE);
 RAISE;
END;
$$;
CREATE TASK IF NOT EXISTS SILVER.PROCESS_ADMISSION_EVENTS
 WAREHOUSE=HOSPITAL_DEV_WH SCHEDULE='1 MINUTE'
 WHEN SYSTEM$STREAM_HAS_DATA('HOSPITAL_DEV.BRONZE.ADMISSION_EVENTS_CDC')
 AS CALL MONITORING.PROCESS_ADMISSION_STREAM();
