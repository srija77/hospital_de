-- Teaching-only synthetic baseline, NOT evidence of equivalence to an actual Phase 5 warehouse.
-- Rebuilt independently from raw batch patients/admissions; compare ALL Gold columns.
CREATE OR REPLACE VIEW SILVER.SYNTHETIC_PHASE5_DIM AS
WITH versions AS (
 SELECT RAW:patient_id::NUMBER(38,0) PATIENT_ID,RAW:patient_name::VARCHAR PATIENT_NAME,
 RAW:email::VARCHAR EMAIL,RAW:phone::VARCHAR PHONE,RAW:date_of_birth::DATE DATE_OF_BIRTH,
 RAW:city::VARCHAR CITY,RAW:updated_at::TIMESTAMP_TZ UPDATED_AT
 FROM BRONZE.PATIENTS
 QUALIFY ROW_NUMBER() OVER (PARTITION BY RAW:patient_id,RAW:updated_at ORDER BY LOADED_AT DESC)=1)
SELECT MD5(PATIENT_ID::VARCHAR||'|'||TO_VARCHAR(UPDATED_AT,'YYYY-MM-DD"T"HH24:MI:SS.FF9TZH:TZM'))::VARCHAR PATIENT_KEY,
 PATIENT_ID,PATIENT_NAME,EMAIL,PHONE,DATE_OF_BIRTH,CITY,UPDATED_AT VALID_FROM,
 LEAD(UPDATED_AT) OVER (PARTITION BY PATIENT_ID ORDER BY UPDATED_AT)::TIMESTAMP_TZ VALID_TO,
 (LEAD(UPDATED_AT) OVER (PARTITION BY PATIENT_ID ORDER BY UPDATED_AT) IS NULL)::BOOLEAN IS_CURRENT FROM versions;
CREATE OR REPLACE VIEW SILVER.SYNTHETIC_PHASE5_FACT AS
WITH batch AS (SELECT RAW FROM BRONZE.ADMISSIONS QUALIFY ROW_NUMBER() OVER
 (PARTITION BY RAW:admission_id ORDER BY LOADED_AT DESC)=1)
SELECT a.RAW:admission_id::NUMBER(38,0) ADMISSION_ID,p.PATIENT_KEY,
 a.RAW:patient_id::NUMBER(38,0) PATIENT_ID,a.RAW:admit_date::DATE ADMIT_DATE,
 a.RAW:discharge_date::DATE DISCHARGE_DATE,a.RAW:department::VARCHAR DEPARTMENT,
 a.RAW:admission_type::VARCHAR ADMISSION_TYPE,a.RAW:bill_amount::NUMBER(18,2) BILL_AMOUNT,
 a.RAW:status::VARCHAR STATUS,a.RAW:updated_at::TIMESTAMP_TZ UPDATED_AT,
 2::NUMBER(38,0) EVENT_VERSION,DATEDIFF('day',ADMIT_DATE,DISCHARGE_DATE)::NUMBER(38,0) LENGTH_OF_STAY
FROM batch a LEFT JOIN SILVER.SYNTHETIC_PHASE5_DIM p
 ON a.RAW:patient_id::NUMBER=p.PATIENT_ID AND a.RAW:admit_date::DATE>=p.VALID_FROM::DATE
 AND (a.RAW:admit_date::DATE<p.VALID_TO::DATE OR p.VALID_TO IS NULL);
SELECT * FROM GOLD.DIM_PATIENTS MINUS SELECT * FROM SILVER.SYNTHETIC_PHASE5_DIM;
SELECT * FROM SILVER.SYNTHETIC_PHASE5_DIM MINUS SELECT * FROM GOLD.DIM_PATIENTS;
SELECT * FROM GOLD.FCT_ADMISSIONS MINUS SELECT * FROM SILVER.SYNTHETIC_PHASE5_FACT;
SELECT * FROM SILVER.SYNTHETIC_PHASE5_FACT MINUS SELECT * FROM GOLD.FCT_ADMISSIONS;
