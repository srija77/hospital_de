-- EXPLICIT DESTRUCTIVE teaching DEV reset. Export evidence first. Never run in PROD.
EXECUTE IMMEDIATE $$
DECLARE
 wrong_context EXCEPTION (-20001,'Reset requires HOSPITAL_DEV and active DE_ENGINEER');
 native_active EXCEPTION (-20002,'Native CDC exists: suspend task, archive campaign, drop CDC stream before explicit reset');
 native_count NUMBER;
BEGIN
 IF (CURRENT_DATABASE() <> 'HOSPITAL_DEV' OR CURRENT_ROLE() <> 'DE_ENGINEER') THEN
  RAISE wrong_context;
 END IF;
 SHOW STREAMS LIKE 'ADMISSION_EVENTS_CDC' IN SCHEMA BRONZE;
 native_count := (SELECT COUNT(*) FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())));
 IF (native_count > 0) THEN
  RAISE native_active;
 END IF;
 TRUNCATE TABLE IF EXISTS BRONZE.PATIENTS;
 TRUNCATE TABLE IF EXISTS BRONZE.ADMISSIONS;
 TRUNCATE TABLE IF EXISTS BRONZE.ADMISSION_EVENTS;
 TRUNCATE TABLE IF EXISTS BRONZE.PIPELINE_RUN_LOG;
 TRUNCATE TABLE IF EXISTS BRONZE.DATA_QUALITY_RESULTS;
 TRUNCATE TABLE IF EXISTS BRONZE.DATA_FRESHNESS;
 TRUNCATE TABLE IF EXISTS BRONZE.BENCHMARK_METADATA;
 TRUNCATE TABLE IF EXISTS SILVER.ADMISSIONS;
 TRUNCATE TABLE IF EXISTS GOLD.FCT_ADMISSIONS;
 TRUNCATE TABLE IF EXISTS GOLD.DIM_PATIENTS;
 RETURN 'Synthetic DEV data reset; COPY table load metadata cleared; monitoring history retained';
END;
$$;
