CREATE OR REPLACE VIEW SILVER.EVENT_CLASSIFICATION AS
SELECT RAW,LOADED_AT,TRY_TO_NUMBER(RAW:admission_id::STRING) ADMISSION_ID,
 TRY_TO_NUMBER(RAW:event_version::STRING) EVENT_VERSION,
 TRY_TO_TIMESTAMP_TZ(RAW:event_time::STRING) EVENT_TIME,RAW:event_id::VARCHAR EVENT_ID,
 COALESCE(RAW:event_type::STRING='UPSERT' AND TRY_TO_NUMBER(RAW:event_version::STRING)>0
 AND TRY_TO_NUMBER(RAW:admission_id::STRING)>0
 AND TRY_TO_NUMBER(RAW:admission_id::STRING)=TRY_TO_NUMBER(RAW:payload:admission_id::STRING)
 AND TRY_TO_NUMBER(RAW:payload:patient_id::STRING)>0
 AND TRY_TO_DECIMAL(RAW:payload:bill_amount::STRING,18,2)>=0
 AND RAW:payload:status::STRING IN ('Admitted','Discharged')
 AND TRY_TO_DATE(RAW:payload:admit_date::STRING) IS NOT NULL
 AND TRY_TO_TIMESTAMP_TZ(RAW:event_time::STRING) IS NOT NULL AND RAW:event_id IS NOT NULL
 AND (RAW:payload:discharge_date IS NULL OR IS_NULL_VALUE(RAW:payload:discharge_date)
 OR TRY_TO_DATE(RAW:payload:discharge_date::STRING)>=TRY_TO_DATE(RAW:payload:admit_date::STRING)),FALSE) IS_VALID
FROM BRONZE.ADMISSION_EVENTS;
CREATE OR REPLACE VIEW SILVER.QUARANTINED_EVENTS AS
 SELECT *,'INVALID_CONTRACT_OR_BUSINESS_RULE' REASON FROM SILVER.EVENT_CLASSIFICATION WHERE NOT IS_VALID;
CREATE OR REPLACE VIEW SILVER.EVENT_WINNERS AS
SELECT * FROM SILVER.EVENT_CLASSIFICATION WHERE IS_VALID
QUALIFY ROW_NUMBER() OVER (PARTITION BY ADMISSION_ID ORDER BY EVENT_VERSION DESC,EVENT_TIME DESC,EVENT_ID DESC)=1;
MERGE INTO SILVER.ADMISSIONS t USING SILVER.EVENT_WINNERS s ON t.ADMISSION_ID=s.ADMISSION_ID
WHEN MATCHED AND (s.EVENT_VERSION>t.EVENT_VERSION OR
 (s.EVENT_VERSION=t.EVENT_VERSION AND s.EVENT_TIME>t.EVENT_TIME) OR
 (s.EVENT_VERSION=t.EVENT_VERSION AND s.EVENT_TIME=t.EVENT_TIME AND s.EVENT_ID>t.EVENT_ID))
THEN UPDATE SET PATIENT_ID=s.RAW:payload:patient_id::NUMBER,ADMIT_DATE=s.RAW:payload:admit_date::DATE,
 DISCHARGE_DATE=s.RAW:payload:discharge_date::DATE,DEPARTMENT=s.RAW:payload:department::VARCHAR,
 ADMISSION_TYPE=s.RAW:payload:admission_type::VARCHAR,BILL_AMOUNT=s.RAW:payload:bill_amount::NUMBER(18,2),
 STATUS=s.RAW:payload:status::VARCHAR,UPDATED_AT=s.RAW:payload:updated_at::TIMESTAMP_TZ,
 EVENT_VERSION=s.EVENT_VERSION,EVENT_TIME=s.EVENT_TIME,EVENT_ID=s.EVENT_ID
WHEN NOT MATCHED THEN INSERT
 (ADMISSION_ID,PATIENT_ID,ADMIT_DATE,DISCHARGE_DATE,DEPARTMENT,ADMISSION_TYPE,BILL_AMOUNT,STATUS,UPDATED_AT,EVENT_VERSION,EVENT_TIME,EVENT_ID)
VALUES (s.ADMISSION_ID,s.RAW:payload:patient_id::NUMBER,s.RAW:payload:admit_date::DATE,
 s.RAW:payload:discharge_date::DATE,s.RAW:payload:department::VARCHAR,s.RAW:payload:admission_type::VARCHAR,
 s.RAW:payload:bill_amount::NUMBER(18,2),s.RAW:payload:status::VARCHAR,
 s.RAW:payload:updated_at::TIMESTAMP_TZ,s.EVENT_VERSION,s.EVENT_TIME,s.EVENT_ID);
CREATE OR REPLACE VIEW SILVER.PATIENT_VERSIONS AS
SELECT RAW:patient_id::NUMBER(38,0) PATIENT_ID,RAW:patient_name::VARCHAR PATIENT_NAME,
 RAW:email::VARCHAR EMAIL,RAW:phone::VARCHAR PHONE,RAW:date_of_birth::DATE DATE_OF_BIRTH,
 RAW:city::VARCHAR CITY,RAW:updated_at::TIMESTAMP_TZ UPDATED_AT
FROM BRONZE.PATIENTS
QUALIFY ROW_NUMBER() OVER (PARTITION BY RAW:patient_id,RAW:updated_at ORDER BY LOADED_AT DESC)=1;
CREATE OR REPLACE VIEW SILVER.SYNTHETIC_PHASE5_BASELINE AS
SELECT RAW:admission_id::NUMBER ADMISSION_ID,RAW:bill_amount::NUMBER(18,2) BILL_AMOUNT
FROM BRONZE.ADMISSIONS
QUALIFY ROW_NUMBER() OVER (PARTITION BY RAW:admission_id ORDER BY LOADED_AT DESC)=1;
