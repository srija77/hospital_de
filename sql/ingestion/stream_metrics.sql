-- Save actual query results hourly and at completion, plus screenshots across 24 hours.
SELECT DATE_TRUNC('minute',LOADED_AT) MINUTE,COUNT(*) EVENTS_PER_MINUTE,
 PERCENTILE_CONT(.5) WITHIN GROUP (ORDER BY DATEDIFF('millisecond',TRY_TO_TIMESTAMP_TZ(RAW:event_time::STRING),LOADED_AT)/1000.0) P50_EVENT_LATENCY_SECONDS,
 PERCENTILE_CONT(.95) WITHIN GROUP (ORDER BY DATEDIFF('millisecond',TRY_TO_TIMESTAMP_TZ(RAW:event_time::STRING),LOADED_AT)/1000.0) P95_EVENT_LATENCY_SECONDS
FROM BRONZE.ADMISSION_EVENTS GROUP BY MINUTE ORDER BY MINUTE;
