-- Requires CREATE ALERT on schema, EXECUTE ALERT on account, warehouse USAGE.
-- DEV only. PROD must explicitly select HOSPITAL_PROD_WH. Starts SUSPENDED.
CREATE ALERT IF NOT EXISTS MONITORING.PIPELINE_FAILURE_ALERT
 WAREHOUSE=HOSPITAL_DEV_WH SCHEDULE='5 MINUTE'
 IF (EXISTS (SELECT 1 FROM MONITORING.FAILURE_DASHBOARD))
 THEN CALL MONITORING.DETECT_ALERTS();
CREATE ALERT IF NOT EXISTS MONITORING.STALE_DATA_ALERT
 WAREHOUSE=HOSPITAL_DEV_WH SCHEDULE='5 MINUTE'
 IF (EXISTS (SELECT 1 FROM MONITORING.FRESHNESS_DASHBOARD WHERE DETECTED_STATUS='STALE'))
 THEN CALL MONITORING.DETECT_ALERTS();
