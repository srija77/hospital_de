MERGE INTO MONITORING.ALERT_EVENTS t USING (
 SELECT 'FAILURE|'||RUN_ID ALERT_KEY,'FAILURE' ALERT_TYPE,PIPELINE_NAME AFFECTED_OBJECT,
 'Failed at '||FAILURE_TIMESTAMP||': '||COALESCE(ERROR_MESSAGE,'unknown') MESSAGE,
 'Inspect run log/query history; fix and replay batch' RECOMMENDED_ACTION
 FROM MONITORING.FAILURE_DASHBOARD
 UNION ALL SELECT 'STALE|'||DATASET_NAME||'|'||COALESCE(LAST_SUCCESSFUL_LOAD::VARCHAR,'NEVER'),'STALE',DATASET_NAME,
 'last_load='||COALESCE(LAST_SUCCESSFUL_LOAD::VARCHAR,'NEVER')||'; age_minutes='||
 COALESCE(ACTUAL_AGE_MINUTES::VARCHAR,'UNKNOWN')||'; threshold_minutes='||EXPECTED_INTERVAL_MINUTES,
 'Inspect ingestion, replay missing batch, verify freshness'
 FROM MONITORING.FRESHNESS_DASHBOARD WHERE DETECTED_STATUS='STALE') s
ON t.ALERT_KEY=s.ALERT_KEY
WHEN NOT MATCHED THEN INSERT VALUES (s.ALERT_KEY,s.ALERT_TYPE,CURRENT_TIMESTAMP(),s.AFFECTED_OBJECT,
 s.MESSAGE,s.RECOMMENDED_ACTION,'Instructor/on-call: MONITORING.ALERT_EVENTS');
