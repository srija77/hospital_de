CREATE OR REPLACE VIEW MONITORING.FRESHNESS_DASHBOARD AS
SELECT *,DATEDIFF('second',LAST_SUCCESSFUL_LOAD,CURRENT_TIMESTAMP())/60.0 ACTUAL_AGE_MINUTES,
 IFF(LAST_SUCCESSFUL_LOAD IS NULL OR DATEDIFF('second',LAST_SUCCESSFUL_LOAD,CURRENT_TIMESTAMP())>EXPECTED_INTERVAL_MINUTES*60,
 'STALE','FRESH') DETECTED_STATUS FROM MONITORING.DATA_FRESHNESS;
CREATE OR REPLACE VIEW MONITORING.ROW_COUNT_DASHBOARD AS
SELECT (SELECT COUNT(*) FROM BRONZE.ADMISSION_EVENTS) BRONZE_COUNT,
 (SELECT COUNT(*) FROM SILVER.ADMISSIONS) SILVER_COUNT,
 (SELECT COUNT(*) FROM GOLD.FCT_ADMISSIONS) GOLD_COUNT,
 BRONZE_COUNT-SILVER_COUNT BRONZE_SILVER_DIFFERENCE,SILVER_COUNT-GOLD_COUNT SILVER_GOLD_DIFFERENCE,
 (SELECT MAX(FINISHED_AT) FROM MONITORING.PIPELINE_RUN_LOG WHERE STATUS='SUCCESS'
 AND PIPELINE_NAME IN ('hospital_load','hospital_native_stream')) LATEST_SUCCESSFUL_RUN;
CREATE OR REPLACE VIEW MONITORING.FAILURE_DASHBOARD AS
SELECT PIPELINE_NAME,RUN_ID,STATUS,FINISHED_AT FAILURE_TIMESTAMP,ERROR_MESSAGE,
 COUNT(*) OVER (PARTITION BY PIPELINE_NAME) FAILURES_LAST_24_HOURS
FROM MONITORING.PIPELINE_RUN_LOG WHERE STATUS='FAILED'
AND FINISHED_AT>=DATEADD('hour',-24,CURRENT_TIMESTAMP());
CREATE OR REPLACE VIEW MONITORING.RUNTIME_DASHBOARD AS
WITH d AS (SELECT *,DATEDIFF('millisecond',STARTED_AT,FINISHED_AT)/1000.0 DURATION_SECONDS
 FROM MONITORING.PIPELINE_RUN_LOG),
p AS (SELECT *,LAG(IFF(STATUS='SUCCESS',DURATION_SECONDS,NULL)) IGNORE NULLS
 OVER (PARTITION BY PIPELINE_NAME,MODEL_NAME ORDER BY STARTED_AT,RUN_ID) PREVIOUS_SUCCESS_SECONDS FROM d)
SELECT *,100.0*(DURATION_SECONDS-PREVIOUS_SUCCESS_SECONDS)/NULLIF(PREVIOUS_SUCCESS_SECONDS,0) CHANGE_PCT FROM p;
