CREATE TABLE IF NOT EXISTS MONITORING.PIPELINE_RUN_LOG (
 RUN_ID VARCHAR,PIPELINE_NAME VARCHAR,MODEL_NAME VARCHAR,STARTED_AT TIMESTAMP_TZ,
 FINISHED_AT TIMESTAMP_TZ,STATUS VARCHAR,ROWS_PROCESSED NUMBER,ERROR_MESSAGE VARCHAR);
CREATE TABLE IF NOT EXISTS MONITORING.DATA_QUALITY_RESULTS (
 CHECK_ID VARCHAR,CHECK_NAME VARCHAR,TABLE_NAME VARCHAR,CHECK_TIMESTAMP TIMESTAMP_TZ,
 STATUS VARCHAR,FAILED_ROW_COUNT NUMBER,SEVERITY VARCHAR,DETAILS VARCHAR);
CREATE TABLE IF NOT EXISTS MONITORING.DATA_FRESHNESS (
 DATASET_NAME VARCHAR,LAST_SUCCESSFUL_LOAD TIMESTAMP_TZ,EXPECTED_INTERVAL_MINUTES NUMBER,
 FRESHNESS_STATUS VARCHAR,ROW_COUNT NUMBER,LAST_CHECKED_AT TIMESTAMP_TZ);
CREATE TABLE IF NOT EXISTS MONITORING.ALERT_EVENTS (
 ALERT_KEY VARCHAR,ALERT_TYPE VARCHAR,DETECTED_AT TIMESTAMP_TZ,AFFECTED_OBJECT VARCHAR,
 MESSAGE VARCHAR,RECOMMENDED_ACTION VARCHAR,RECIPIENT VARCHAR);
CREATE TABLE IF NOT EXISTS MONITORING.BENCHMARK_METADATA (
 BENCHMARK_ID VARCHAR,WORKLOAD_NAME VARCHAR,RUN_TIMESTAMP TIMESTAMP_TZ,CONFIGURATION_NAME VARCHAR,
 ELAPSED_SECONDS FLOAT,BYTES_SCANNED NUMBER,ROWS_RETURNED NUMBER,WAREHOUSE_NAME VARCHAR,
 CREDITS_USED FLOAT,CACHE_STATE VARCHAR,QUERY_ID VARCHAR,QUERY_TEXT VARCHAR,WAREHOUSE_SIZE VARCHAR,
 EXPERIMENT VARCHAR,VARIANT VARCHAR,EVIDENCE VARCHAR);
