SELECT DATE_TRUNC('minute',LOADED_AT) MINUTE,COUNT(*) EVENTS_PER_MINUTE,
 PERCENTILE_CONT(.5) WITHIN GROUP (ORDER BY DATEDIFF('millisecond',SOURCE_PUBLISHED_AT,LOADED_AT)/1000.0) P50_SEND_TO_SERVER_SECONDS,
 PERCENTILE_CONT(.95) WITHIN GROUP (ORDER BY DATEDIFF('millisecond',SOURCE_PUBLISHED_AT,LOADED_AT)/1000.0) P95_SEND_TO_SERVER_SECONDS
FROM BRONZE.ADMISSION_EVENTS WHERE SOURCE_PUBLISHED_AT IS NOT NULL
GROUP BY MINUTE ORDER BY MINUTE;
