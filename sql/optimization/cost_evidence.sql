-- Cost attribution can lag and requires appropriate SNOWFLAKE database role.
-- Missing query attribution stays NULL; warehouse totals are not query credits.
SELECT QUERY_ID,CREDITS_ATTRIBUTED_COMPUTE
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_ATTRIBUTION_HISTORY
WHERE QUERY_ID IN (SELECT QUERY_ID FROM MONITORING.BENCHMARK_METADATA);
SELECT START_TIME,END_TIME,WAREHOUSE_NAME,CREDITS_USED_COMPUTE,CREDITS_USED_CLOUD_SERVICES
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE WAREHOUSE_NAME='HOSPITAL_DEV_WH' AND START_TIME>=DATEADD('day',-1,CURRENT_TIMESTAMP());
-- Billing totals include idle/minimum billing and may differ from attributed query credits.
