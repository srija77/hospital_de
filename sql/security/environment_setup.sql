-- One-time SYSADMIN bootstrap. Role assignment requires SECURITYADMIN.
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS DE_ADMIN;
CREATE ROLE IF NOT EXISTS DE_ENGINEER;
CREATE ROLE IF NOT EXISTS DE_ANALYST;
CREATE ROLE IF NOT EXISTS DE_DEPLOYER;
GRANT ROLE DE_ENGINEER TO ROLE DE_ADMIN;
GRANT ROLE DE_ANALYST TO ROLE DE_ADMIN;
GRANT ROLE DE_DEPLOYER TO ROLE DE_ADMIN;
GRANT ROLE DE_ADMIN TO ROLE SYSADMIN;
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS HOSPITAL_DEV_WH WAREHOUSE_SIZE=XSMALL AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE;
CREATE WAREHOUSE IF NOT EXISTS HOSPITAL_PROD_WH WAREHOUSE_SIZE=XSMALL AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE;
CREATE DATABASE IF NOT EXISTS HOSPITAL_DEV;
CREATE DATABASE IF NOT EXISTS HOSPITAL_PROD;
GRANT OWNERSHIP ON DATABASE HOSPITAL_DEV TO ROLE DE_ENGINEER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE HOSPITAL_PROD TO ROLE DE_DEPLOYER COPY CURRENT GRANTS;
GRANT USAGE ON WAREHOUSE HOSPITAL_DEV_WH TO ROLE DE_ENGINEER;
GRANT USAGE ON WAREHOUSE HOSPITAL_PROD_WH TO ROLE DE_DEPLOYER;
GRANT USAGE ON WAREHOUSE HOSPITAL_PROD_WH TO ROLE DE_ANALYST;
-- Assign each role to separate users. DE_DEPLOYER belongs only to PROD automation.
